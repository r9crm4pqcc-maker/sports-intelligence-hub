const lookup = (entries: readonly PlayerEntry[]) =>
  new Map(entries.map(([team, player]) => [normalizeSportsName(team), player]));

const GROUPS: Record<PlayerGroup, Map<string, string>> = {
  nba: lookup(NBA),
  collegeBasketball: lookup(COLLEGE_BASKETBALL),
  soccer: lookup(SOCCER),
};

export function listedKeyPlayer(
  teamName: string,
  group: PlayerGroup,
): string | undefined {
  const normalized = normalizeSportsName(teamName);
  const entries = GROUPS[group];
  const exact = entries.get(normalized);
  if (exact) return exact;
  for (const [team, player] of entries) {
    if (normalized.startsWith(`${team} `)) return player;
  }
  return undefined;
}

export function keyPlayerListCounts(): Record<PlayerGroup, number> {
  return { nba: 30, collegeBasketball: 79, soccer: 35 };
}
