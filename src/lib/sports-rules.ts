/** Stable id for one vote reason, so "Hawks are best friends with the 9 day" and "Celtics are best friends with the 4 day" are the same signal. */
export function ruleId(reason: string): string {
  const s = reason.toLowerCase();
  if (s.includes("five-cipher name/date/record match")) return "learned-screenshot-gematria";
  if (s.includes("western astrology:")) return "western-sign-compatibility";
  if (s.includes("recent form gap")) return "recent-form";
  if (s.includes("home and road gap")) return "home-road";
  if (s.includes("back to back")) return "rest";
  if (s.includes("injury count")) return "injuries";
  if (s.includes("head to head gap")) return "h2h";
  if (s.includes("team rating")) return "team-rating";
  if (s.includes("record margin")) return "record-margin";
  if (s.includes("home field")) return "home-field";
  if (s.includes("better record gap 50")) return "record-gap-50";
  if (s.includes("better record gap 40")) return "record-gap-40";
  if (s.includes("better record gap 30")) return "record-gap-30";
  if (s.includes("better record gap 15")) return "record-gap-15";
  if (s.includes("tiebreaker")) return "record-tiebreak";
  if (s.includes("vibrates at 9")) return "record-9-penalty";
  if (s.includes("worst-enemy")) return "lifepath-worst-day";
  if (s.includes("— enemies") || s.includes("universal day — enemies")) return "lifepath-enemy-day";
  if (s.includes("soulmates with")) return "lifepath-soulmate-day";
  if (s.includes("best friends with")) return "lifepath-friend-day";
  if (s.includes("stronger signature")) return "core-stronger";
  if (s.includes("master multiplier")) return "core-master";
  if (s.includes("enemy of the")) return "personal-day-enemy";
  if (s.includes("matches") && s.includes("universal day")) return "personal-day-match";
  if (s.includes("friendly with the") && s.includes("universal day")) return "personal-day-friend";
  if (s.includes("touches today")) return "touches-today";
  if (s.includes("enemy year")) return "zodiac-enemy-year";
  if (s.includes("shares a trine")) return "zodiac-trine";
  if (s.includes("secret enemies") && s.includes("year")) return "zodiac-secret-enemy-year";
  if (s.includes("secret friends") && s.includes("year")) return "zodiac-secret-friend-year";
  if (s.includes("secret enemies") && s.includes("month")) return "zodiac-secret-enemy-month";
  if (s.includes("secret friends") && s.includes("month")) return "zodiac-secret-friend-month";
  if (s.includes("secret enemies with")) return "zodiac-secret-enemy-opponent";
  if (s.includes("secret friends with")) return "zodiac-secret-friend-opponent";
  if (s.includes("clashes with")) return "player-clash-opponent";
  if (s.includes("is friendly with")) return "player-friend-opponent";
  if (s.includes("hour flips to friend")) return "hour-close-friend";
  if (s.includes("hour flips to enemy")) return "hour-close-enemy";
  if (s.includes("favorite modifier")) return "moon-favorite";
  if (s.includes("underdog modifier")) return "moon-underdog";
  if (s.includes("both against")) return "venue-both-against";
  if (s.includes("wealth-day")) return "wealth-day-favorite";
  if (s.includes("week-of-year")) return "week-root";
  if (s.includes("day-of-year")) return "day-of-year-root";
  if (s.includes("new moon")) return "moon-new-road";
  if (s.includes("full moon")) return "moon-full-home";
  if (s.includes("— beneficial") || s.includes("— soulmate") || s.includes("— lovers")) return "venue-friendly";
  if (s.includes("— challenging") || s.includes("— fatal")) return "venue-against";
  if (s.startsWith("stadium") && s.includes("matches today")) return "stadium-matches-today";
  if (s.startsWith("city") && s.includes("matches today")) return "city-matches-today";
  if (s.includes("matches today")) return "player-born-today";
  if (s.includes("scores with")) return "jersey-match";
  if (s.includes("birth card")) return "birth-card-match";
  if (s.includes("close stack")) return "close-stack";
  if (s.includes("full point penalty")) return "venue-both-against";
  return "other";
}
